def _load_lookup() -> dict[str, dict[str, str | None]]:
    """Load the FAERS/AACT lookup table from JSON, enriched with verified PT codes."""
    lookup: dict[str, dict[str, str | None]] = {}

    if _LOOKUP_PATH.exists():
        try:
            with open(_LOOKUP_PATH, encoding="utf-8") as f:
                data = json.load(f)
            raw_terms = data.get("terms", {})
            for key, info in raw_terms.items():
                pt_name = info.get("pt", key.title())
                pt_lower = pt_name.strip().lower()
                # Look up verified code by key or PT name
                pt_code = _VERIFIED_PT_CODES.get(key) or _VERIFIED_PT_CODES.get(pt_lower)
                lookup[key] = {
                    "pt": pt_name,
                    "pt_code": pt_code,
                    "soc": info.get("soc"),
                    "llt": info.get("llt", pt_name),
                }
            logger.info(
                "MedDRA lookup loaded: %d terms from %s", len(lookup), _LOOKUP_PATH,
            )
        except Exception:
            logger.exception("Failed to load MedDRA lookup from %s", _LOOKUP_PATH)
    else:
        logger.warning(
            "MedDRA lookup file not found: %s — run scripts/build_meddra_lookup.py",
            _LOOKUP_PATH,
        )

    # Add aliases
    for alias, canonical in _ALIASES.items():
        if canonical in lookup and alias not in lookup:
            entry = dict(lookup[canonical])
            entry["llt"] = alias.title()  # LLT = the alias form
            lookup[alias] = entry

    return lookup


FAERS_LOOKUP: dict[str, dict[str, str | None]] = _load_lookup()


# ---------------------------------------------------------------------------
# Step ②: MedGemma fallback
# ---------------------------------------------------------------------------

def _code_via_medgemma(
    term: str,
    base_url: str = "http://localhost:38000/v1",
    model_id: str = "google/medgemma-27b-it",
    api_key: str = "EMPTY",
) -> MedDRACode:
    """Call MedGemma 27B to infer MedDRA coding for an unknown AE term."""
    client = OpenAI(base_url=base_url, api_key=api_key)

    prompt = MEDGEMMA_MEDDRA_PROMPT.format(ae_term=term)

    response = client.chat.completions.create(
        model=model_id,
        messages=[{"role": "user", "content": prompt}],
        max_tokens=256,
        temperature=0.1,
    )

    raw = response.choices[0].message.content.strip()

    # Strip markdown code fences if present
    if raw.startswith("```"):
        raw = raw.split("\n", 1)[1] if "\n" in raw else raw[3:]
        if raw.endswith("```"):
            raw = raw[:-3]
        raw = raw.strip()

    parsed = json.loads(raw)
    confidence = float(parsed.get("confidence", 0.0))

    source = "medgemma" if confidence >= MEDDRA_CONFIDENCE_THRESHOLD else "manual_review"
    if source == "manual_review":
        logger.warning(
            "MedDRA coding low confidence for '%s': %.2f < %.2f — flagged for manual review",
            term, confidence, MEDDRA_CONFIDENCE_THRESHOLD,
        )

    return MedDRACode(
        pt=parsed.get("pt", term),
        pt_code=parsed.get("pt_code"),
        soc=parsed.get("soc"),
        llt=parsed.get("llt", term),
        confidence=confidence,
        source=source,
    )


