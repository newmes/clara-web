logger = logging.getLogger(__name__)

MEDDRA_CONFIDENCE_THRESHOLD = 0.85

MEDGEMMA_MEDDRA_PROMPT = """\
You are a pharmacovigilance coding specialist. Given an adverse event term reported in a clinical trial, \
provide the most accurate MedDRA coding.

Adverse Event Term: "{ae_term}"

Respond ONLY with a JSON object (no markdown, no explanation):
{{
  "pt": "MedDRA Preferred Term",
  "pt_code": "MedDRA PT code (8-digit number)",
  "soc": "System Organ Class",
  "llt": "Lowest Level Term (closest to the reported term)",
  "confidence": 0.95
}}

Rules:
- Use MedDRA v26.1 terminology
- PT must be an official MedDRA Preferred Term
- SOC must be one of the 27 official MedDRA System Organ Classes
- LLT should be the closest match to the original reported term
- confidence: 0.0-1.0, how certain you are this is the correct PT mapping
- If unsure, set confidence below 0.85
"""

