# Public API
# ---------------------------------------------------------------------------

def code_meddra(
    term: str,
    use_medgemma: bool = True,
    base_url: str = "http://localhost:38000/v1",
    model_id: str = "google/medgemma-27b-it",
    api_key: str = "EMPTY",
) -> MedDRACode:
    """Look up MedDRA coding for an AE term.

    Strategy (3-step, doc_agent.md §6.6):
      ① AACT/FAERS lookup table matching → highest accuracy
      ② MedGemma 27B inference → confidence score
      ③ Manual review flag → confidence < 0.85
    """
    # Step ①: FAERS/AACT lookup table
    key = term.strip().lower()
    if key in FAERS_LOOKUP:
        entry = FAERS_LOOKUP[key]
        return MedDRACode(
            pt=entry["pt"],
            pt_code=entry.get("pt_code"),
            soc=entry.get("soc"),
            llt=entry.get("llt"),
            confidence=1.0,
            source="lookup",
        )

    # Step ② + ③: MedGemma fallback (with auto manual_review flag)
    if use_medgemma:
        try:
            result = _code_via_medgemma(term, base_url, model_id, api_key)
            logger.info(
                "MedDRA via MedGemma: '%s' → PT='%s' (confidence=%.2f, source=%s)",
                term, result.pt, result.confidence or 0.0, result.source,
            )
            return result
        except Exception:
            logger.exception("MedGemma MedDRA coding failed for '%s', returning raw term", term)

    # Final fallback: return term as-is, flagged for manual review
    return MedDRACode(
        pt=term,
        pt_code=None,
        soc=None,
        llt=term,
        confidence=0.0,
        source="manual_review",
    )
