"""MedDRA coding module — lookup table + MedGemma fallback.

Strategy (doc_agent.md §6.6):
  ① AACT/FAERS lookup table matching (highest accuracy)
  ② MedGemma 27B inference with confidence score
  ③ Manual review flag (low confidence < 0.85)

Lookup table is loaded from ``data/meddra_lookup.json``, which is generated
by ``scripts/build_meddra_lookup.py`` using openFDA FAERS + optional AACT data.
"""
